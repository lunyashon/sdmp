CREATE TABLE IF NOT EXISTS skorozvon_link (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR NOT NULL,
	"type" VARCHAR NOT NULL,
	project_id BIGINT NOT NULL REFERENCES skorozvon_project(project_id),
	created_at TIMESTAMP NOT NULL
);

COMMENT ON TABLE skorozvon_link IS 'Связка: под-источники + регионы → проект Скорозвона. type=dup|uniq. 1 под-источник = стандартная, 2+ = кастомная. Пустые регионы = все';
COMMENT ON COLUMN skorozvon_link."type" IS 'dup = работа с дублями, uniq = работа с униками';
COMMENT ON COLUMN skorozvon_link.project_id IS 'call_project_id из skorozvon_project';

CREATE TABLE IF NOT EXISTS skorozvon_link_source (
	link_id INT NOT NULL REFERENCES skorozvon_link(id) ON DELETE CASCADE,
	source_id INT NOT NULL REFERENCES source(id),
	PRIMARY KEY (link_id, source_id)
);

COMMENT ON TABLE skorozvon_link_source IS 'Под-источники связки';

CREATE TABLE IF NOT EXISTS skorozvon_link_region (
	link_id INT NOT NULL REFERENCES skorozvon_link(id) ON DELETE CASCADE,
	region_id INT NOT NULL REFERENCES region(id),
	PRIMARY KEY (link_id, region_id)
);

COMMENT ON TABLE skorozvon_link_region IS 'Разрешённые регионы связки. Пусто = регион не проверяется';
