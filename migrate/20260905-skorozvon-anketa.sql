CREATE TABLE IF NOT EXISTS skorozvon_anketa (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	lead_row_id BIGINT NOT NULL REFERENCES lead_row (id),
	skorozvon_lead_id VARCHAR NOT NULL,
	call_id VARCHAR,
	user_id BIGINT,
	form_id BIGINT,
	scenario_id BIGINT,
	form_name VARCHAR,
	answers VARCHAR NOT NULL DEFAULT '[]',
	form_updated_at TIMESTAMP,
	created_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS skorozvon_anketa_lead_row_id_idx
	ON skorozvon_anketa (lead_row_id, id DESC);

COMMENT ON TABLE skorozvon_anketa IS 'анкета Скорозвона из webhook form_response. История: одна строка на событие. Актуальная — lead_row.skorozvon_anketa_id';
COMMENT ON COLUMN skorozvon_anketa.lead_row_id IS 'наша строка. Ищем по lead_row.skorozvon_lead_id = lead.id из webhook';
COMMENT ON COLUMN skorozvon_anketa.skorozvon_lead_id IS 'lead.id из Скорозвона';
COMMENT ON COLUMN skorozvon_anketa.call_id IS 'call.id из webhook. Nullable';
COMMENT ON COLUMN skorozvon_anketa.answers IS 'json-массив answers: question_id, question_name, answer_id, answer_values';
COMMENT ON COLUMN skorozvon_anketa.form_updated_at IS 'form_response.updated_at из Скорозвона';

ALTER TABLE lead_row
	ADD COLUMN IF NOT EXISTS skorozvon_anketa_id BIGINT;

DO $$
BEGIN
	IF NOT EXISTS (
		SELECT 1 FROM pg_constraint WHERE conname = 'lead_row_skorozvon_anketa_id_fkey'
	) THEN
		ALTER TABLE lead_row
			ADD CONSTRAINT lead_row_skorozvon_anketa_id_fkey
			FOREIGN KEY (skorozvon_anketa_id) REFERENCES skorozvon_anketa (id);
	END IF;
END $$;

COMMENT ON COLUMN lead_row.skorozvon_anketa_id IS 'актуальная анкета Скорозвона. История в skorozvon_anketa. Старый call_form не трогаем';
