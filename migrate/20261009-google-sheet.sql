CREATE TABLE IF NOT EXISTS google_sheet (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT NOT NULL,
	spreadsheet_id TEXT NOT NULL,
	sheet_name TEXT NOT NULL,
	credentials JSONB NOT NULL DEFAULT '{}'::jsonb,
	test_mode BOOLEAN NOT NULL DEFAULT false,
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE google_sheet IS 'Инстанс интеграции Google Sheets: сервисный аккаунт + таблица. Логику записи настраивают отдельно';
COMMENT ON COLUMN google_sheet.credentials IS 'JSON ключа service_account. В API наружу не отдаём, только client_email / project_id / has_key';
COMMENT ON COLUMN google_sheet.spreadsheet_id IS 'ID таблицы из URL docs.google.com/spreadsheets/d/{id}';
COMMENT ON COLUMN google_sheet.sheet_name IS 'Имя листа внутри таблицы';
COMMENT ON COLUMN google_sheet.test_mode IS 'Флаг для внешней логики записи; API его только хранит';
