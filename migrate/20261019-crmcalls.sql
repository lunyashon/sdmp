CREATE TABLE IF NOT EXISTS crmcalls_project (
	id VARCHAR PRIMARY KEY,
	name VARCHAR NOT NULL DEFAULT '',
	status VARCHAR NOT NULL DEFAULT '',
	updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE crmcalls_project IS 'Кэш проектов CRMCalls (UUID). Список для связок дубли/уники';

CREATE TABLE IF NOT EXISTS crmcalls_link (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR NOT NULL,
	"type" VARCHAR NOT NULL,
	project_id VARCHAR NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE crmcalls_link IS 'Связка: под-источники + регионы → проект CRMCalls. type=dup|uniq. Пустые регионы = все';
COMMENT ON COLUMN crmcalls_link."type" IS 'dup = работа с дублями, uniq = работа с униками';
COMMENT ON COLUMN crmcalls_link.project_id IS 'UUID проекта CRMCalls';

CREATE TABLE IF NOT EXISTS crmcalls_link_source (
	link_id INT NOT NULL REFERENCES crmcalls_link(id) ON DELETE CASCADE,
	source_id INT NOT NULL REFERENCES source(id),
	PRIMARY KEY (link_id, source_id)
);

CREATE TABLE IF NOT EXISTS crmcalls_link_region (
	link_id INT NOT NULL REFERENCES crmcalls_link(id) ON DELETE CASCADE,
	region_id INT NOT NULL REFERENCES region(id),
	PRIMARY KEY (link_id, region_id)
);

CREATE TABLE IF NOT EXISTS lead_crmcalls (
	contact_id VARCHAR PRIMARY KEY,
	lead_row_id BIGINT NOT NULL REFERENCES lead_row(id),
	project_id VARCHAR
);

CREATE INDEX IF NOT EXISTS lead_crmcalls_lead_idx ON lead_crmcalls (lead_row_id);

COMMENT ON TABLE lead_crmcalls IS 'Связка нашей строки с контактом CRMCalls. Ищем постбэк по contact_id';

CREATE TABLE IF NOT EXISTS outbox_crmcalls (
	uuid VARCHAR PRIMARY KEY,
	uuid_lead VARCHAR NOT NULL REFERENCES lead_row (uuid),
	locked_until TIMESTAMPTZ,
	count_retry SMALLINT NOT NULL DEFAULT 0,
	last_retry TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS outbox_crmcalls_uuid_lead_uidx ON outbox_crmcalls (uuid_lead);
CREATE INDEX IF NOT EXISTS outbox_crmcalls_claim_idx ON outbox_crmcalls (uuid)
	WHERE count_retry < 6;

COMMENT ON TABLE outbox_crmcalls IS 'очередь отправки в CRMCalls. Пишем после обогащения. Claim отдельной горутиной';
