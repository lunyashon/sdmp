-- phone.search territory formats (~окт.2026): «Город Москва, …», «…область-Кузбасс».
-- ResolveRegion also tries normalized variants; these aliases cover the raw strings 1:1.

INSERT INTO region_alias (alias, region_id)
SELECT v.alias, v.region_id
FROM (VALUES
	('Город Москва, Московская область', 17),
	('Московская область, Город Москва', 17),
	('Город Москва', 17),
	('Город Санкт-Петербург, Ленинградская область', 23),
	('Ленинградская область, Город Санкт-Петербург', 23),
	('Город Санкт-Петербург', 23),
	('Кемеровская область-Кузбасс', 24),
	('Чувашская Республика-Чувашия', 87),
	('Республика Северная Осетия-Алания', 59),
	('Архангельская область, Ненецкий автономный округ', 89),
	('Республика Крым, Город Севастополь', 58),
	('Город Севастополь, Республика Крым', 58),
	('Московская область и г. Москва', 17),
	('Ленинградская область и г. Санкт-Петербург', 23)
) AS v(alias, region_id)
WHERE NOT EXISTS (
	SELECT 1 FROM region_alias a WHERE lower(a.alias) = lower(v.alias)
);
